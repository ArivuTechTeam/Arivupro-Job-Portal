import { createClient } from '@supabase/supabase-js';
import type { Database } from './types';

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;

if (!supabaseUrl || !supabaseAnonKey) {
  throw new Error('Missing VITE_SUPABASE_URL or VITE_SUPABASE_ANON_KEY in .env');
}

// Use sessionStorage so each tab has its own Supabase session.
// The app role is stored separately in sessionStorage under 'ap_auth' and is
// the authoritative source of truth — the Supabase session is only used to
// obtain a fresh JWT for API calls.
export const supabase = createClient<Database>(supabaseUrl, supabaseAnonKey, {
  auth: {
    persistSession: true,
    autoRefreshToken: true,
    detectSessionInUrl: true,
    storageKey: 'arivupro-auth',
    storage: window.sessionStorage,
  },
});
